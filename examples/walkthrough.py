#!/usr/bin/env python3
"""Print a worked extraction example using artificial data, without game files.

Uses the same tiny fixture builders as the tests so the prose can be checked
against the production parsers. This is not an independent format oracle.
"""
from __future__ import annotations

import argparse
from fractions import Fraction
import json
from pathlib import Path
import struct
import sys
import tempfile
import zlib

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

import synthetic
from arcade import import_ifs as arcade
from mobile import extract as mobile
from mobile.tools.cgbi import cgbi_to_png


def check(actual, expected, label):
    if actual != expected:
        raise RuntimeError(f"{label}: expected {expected!r}, got {actual!r}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--skip-decrypt", action="store_true",
                        help="skip compiling/running the C decryptor; keep all other steps")
    args = parser.parse_args()
    print("All bytes below are artificial. No game files or audio encoder needed.")

    print("\n1. CBC envelope: five plaintext bytes, one eight-byte cipher block")
    wrapped = synthetic.encrypted(b"hello")
    plain_len, cipher_len = struct.unpack_from(">II", wrapped, len(wrapped) - 8)
    check((plain_len, cipher_len), (5, 8), "CBC lengths")
    print("ciphertext:", wrapped[:-8].hex(" "))
    print("footer:    ", wrapped[-8:].hex(" "), "=> plen=5, clen=8")
    decode = None
    if args.skip_decrypt:
        print("C decryption skipped explicitly; envelope generated by Python reference cipher.")
    else:
        decode = mobile.Decryptor()
        check(decode(wrapped), b"hello", "CBC plaintext")
        print("C decrypt ->", repr(decode(wrapped)))

    print("\n2. Mobile sequence: 0x60-byte header, six eight-byte records")
    seq = synthetic.sequence()
    if decode is not None:
        check(decode(synthetic.encrypted(seq)), seq, "sequence round trip")
    records = mobile.parse_seq(seq)[-1]
    for number, (kind, tick, value) in enumerate(records):
        offset = 0x60 + 8 * number
        print(f"0x{offset:02x}: {seq[offset:offset + 8].hex(' ')}"
              f" => type={kind}, tick={tick}, value={value}")

    print("\n3. Packed hold and piecewise tempo")
    value = records[2][2]
    fields = (value & 15, (value >> 4) & 3, (value >> 6) & 3, value >> 8)
    check(fields, (0, 1, 1, 300), "hold fields")
    print(f"LONG {value} (0x{value:08x}): index, direction, length, duration = {fields}")
    chart = mobile.parse_chart(seq)
    expected_notes = [(Fraction(0), 0, None, None),
                      (Fraction(2), 0, Fraction(4), 4),
                      (Fraction(5), 2, None, None)]
    check(chart["notes"], expected_notes, "worked note values")
    check(chart["timing"], [(Fraction(0), Fraction(120)),
                            (Fraction(4), Fraction(60))], "worked tempo values")
    for beat, index, endbeat, endindex in chart["notes"]:
        print(f"beat={beat}, index={index}, endbeat={endbeat}, endindex={endindex}")
    check(mobile.value_to_bpm(333333), Fraction(180), "truncated tempo recovery")
    print("TEMPO 333333: direct division =", float(Fraction(60000000, 333333)),
          "; shortest valid decimal =", mobile.value_to_bpm(333333))
    print("note entries, scoring count, holds =", len(chart["notes"]), *mobile.volume(chart["notes"]))

    print("\n4. Artificial IFS: same events, different container")
    with tempfile.TemporaryDirectory(prefix="jubeat-walkthrough-") as temporary:
        path = Path(temporary) / "synthetic.ifs"
        path.write_bytes(synthetic.ifs_bytes())
        data, entries = arcade.load_ifs(path)
        base = struct.unpack_from(">I", data, 0x10)[0]
        print(f"base=0x{base:02x}, table_start=0x{base - 60:02x}")
        for i, (offset, size) in enumerate(entries):
            print(f"block {i}: relative=0x{offset - base:02x}, absolute=0x{offset:02x}, size={size}")
        notes, timing, offset = arcade.parse_chart(path, "EXT")
        check((notes, timing, offset), (chart["notes"], chart["timing"], Fraction(0)),
              "IFS/mobile agreement")
    print("IFS notes and tempo match the mobile example.")

    print("\n5. One ADPCM byte: independent left/right predictor histories")
    audio = bytearray(0x20)
    audio[:4] = b"BMP\0"
    struct.pack_into(">I", audio, 4, 1)
    audio[0x10] = 2
    struct.pack_into(">I", audio, 0x14, 8000)
    pcm, rate, channels = arcade.decode_bmp_to_pcm(bytes(audio) + b"\x10")
    check((pcm, rate, channels), (bytes.fromhex("60 00 20 00"), 8000, 2), "ADPCM sample")
    print("0x10 -> left code=1, right code=0 -> PCM samples", struct.unpack("<hh", pcm))
    print("little-endian PCM bytes:", pcm.hex(" "))

    print("\n6. One CgBI pixel: unfilter, swap channels, undo alpha multiplication")
    png = cgbi_to_png(synthetic.cgbi())
    idat = png.index(b"IDAT")  # Safe for this fixed artificial fixture only.
    length = struct.unpack_from(">I", png, idat - 4)[0]
    row = zlib.decompress(png[idat + 4:idat + 4 + length])
    check(row, bytes([0, 199, 100, 50, 128]), "CgBI pixel")
    print("premultiplied BGRA [25, 50, 100, 128] -> straight RGBA", list(row[1:]))

    print("\n7. Relevant .mc JSON fields (no audio or cover reference in this example)")
    mc = json.loads(mobile.write_chart_mc(chart["notes"], chart["timing"],
                                         "Synthetic Song", "Synthetic Artist",
                                         "ext", 7, "", ""))
    print(json.dumps({"time": mc["time"], "note": mc["note"]}, indent=2))
    print("\nPASS: all displayed results checked against explicit expected values or both parsers.")


if __name__ == "__main__":
    main()
